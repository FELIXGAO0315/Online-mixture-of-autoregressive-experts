"""Run the complete pipeline in order and write outputs/SUMMARY.md.

    python experiments/run_all.py              # unit tests + steps 01..06 (~15 min on a 16-core laptop)
    python experiments/run_all.py --quick      # reduced tuning grids and 1 ablation seed (smoke test)
    python experiments/run_all.py --from 05    # resume from a step
    python experiments/run_all.py --jobs 4     # limit the number of worker processes
"""
import _bootstrap  # noqa: F401

import argparse
import os
import subprocess
import sys
import time
from pathlib import Path

if "--quick" in sys.argv:  # must happen before omar.config is imported (here and in every child process)
    os.environ.setdefault("OMAR_OUTPUTS", str(Path(__file__).resolve().parents[1] / "outputs_quick"))

from omar import config  # noqa: E402

HERE = Path(__file__).resolve().parent
STEPS = [
    ("01", "01_prepare_data.py", False, False),  # (id, script, takes --jobs, takes --quick)
    ("02", "02_check_experts.py", True, False),
    ("03", "03_tune.py", True, True),
    ("04", "04_sanity.py", True, False),
    ("05", "05_main.py", True, False),
    ("06", "06_ablation.py", True, True),
]

SUMMARY_TABLES = [
    ("Datasets", config.OUT_DATA / "tables" / "datasets.md"),
    ("Selected hyperparameters", config.OUT_TUNING / "tables" / "selected_hparams.md"),
    ("Levinson-Durbin vs direct solve", config.OUT_EXPERTS / "tables" / "levinson_vs_direct.md"),
    ("Stability guard", config.OUT_EXPERTS / "tables" / "guard_stats.md"),
    ("Sanity (a)", config.OUT_SANITY / "tables" / "a_frozen_residual_equals_alg1.md"),
    ("Sanity (b)", config.OUT_SANITY / "tables" / "b_stationary_matches_best_and_fpe.md"),
    ("Sanity (c)", config.OUT_SANITY / "tables" / "c_no_lookahead.md"),
    ("Main: synthetic n=1", config.OUT_MAIN / "tables" / "main_synthetic_n1.md"),
    ("Main: synthetic n=3", config.OUT_MAIN / "tables" / "main_synthetic_n3.md"),
    ("Main: real data", config.OUT_MAIN / "tables" / "main_real.md"),
    ("Relative to best expert", config.OUT_MAIN / "tables" / "relative_to_best_expert.md"),
    ("Proposed vs Algorithm 1", config.OUT_MAIN / "tables" / "proposed_vs_alg1.md"),
    ("Re-adaptation", config.OUT_MAIN / "tables" / "readaptation.md"),
    ("Learning ladder", config.OUT_ABLATION / "tables" / "b_learning_ladder.md"),
    ("Characterization", config.OUT_ABLATION / "tables" / "d_characterization.md"),
    ("Heterogeneous experts", config.OUT_ABLATION / "tables" / "c_heterogeneous_experts.md"),
]


def write_summary() -> None:
    parts = ["# Results summary (auto-generated by experiments/run_all.py)\n",
             "Every table below is also available as CSV next to its Markdown file; all figures are in "
             "`outputs/*/figures/` (PNG + PDF).\n"]
    for title, path in SUMMARY_TABLES:
        if path.exists():
            rel = Path(os.path.relpath(path, config.ROOT)).as_posix()
            parts.append(f"## {title}\n\nSource: `{rel}`\n\n{path.read_text(encoding='utf-8')}\n")
    (config.OUTPUTS / "SUMMARY.md").write_text("\n".join(parts), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--jobs", type=int, default=None, help="worker processes (default: min(8, cpus-1))")
    ap.add_argument("--quick", action="store_true", help="reduced grids / 1 ablation seed")
    ap.add_argument("--from", dest="start", default="01", help="first step to run (01..06)")
    ap.add_argument("--skip-tests", action="store_true", help="do not run the unit tests first")
    args = ap.parse_args()
    t0 = time.time()
    if not args.skip_tests and args.start == "01":
        print("=== unit tests ===", flush=True)
        subprocess.run([sys.executable, "-m", "pytest", "-q", str(config.ROOT / "tests")], check=True, cwd=config.ROOT)
    for sid, script, takes_jobs, takes_quick in STEPS:
        if sid < args.start:
            continue
        cmd = [sys.executable, str(HERE / script)]
        if takes_jobs and args.jobs is not None:
            cmd += ["--jobs", str(args.jobs)]
        if takes_quick and args.quick:
            cmd += ["--quick"]
        print(f"\n=== step {sid}: {script} ({time.time() - t0:.0f}s elapsed) ===", flush=True)
        subprocess.run(cmd, check=True, cwd=config.ROOT)
    write_summary()
    print(f"\nall done in {time.time() - t0:.0f}s -> {config.OUTPUTS} (see outputs/SUMMARY.md)")


if __name__ == "__main__":
    main()
